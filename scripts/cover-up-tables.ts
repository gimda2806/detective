// ─── 선언이 문장보다 좁은가 ─────────────────────────────────────────────
//
// 선언은 폴백을 **대체**하므로 문장보다 좁은 선언은 그 축을 그만큼 통째로 안
// 세어지게 한다(CASE022: 은폐 한 문장에 손놀림이 넷인데 선언은 하나, 경고 0).
// 폴백 정규식을 선언과 **같이** 돌려 「폴백이 더 잡는 칸」을 센다.
//
// 그대로 세면 60%가 걸리는데 대부분 잡음이라(2026-09-26 실측, 298건), 셋을 거른다:
//   ① 읽는 글은 `cover_up` 문장만 — 살해 수법 문장(`method`)의 「노후·고장」은
//      수단이지 은폐가 아니다 (60% → 47%)
//   ② 사고 위장 다섯 칸은 한 계열 — 「무엇을 탓하나」는 정규식이 못 가르는 차이라,
//      선언에 사고 위장 칸이 하나라도 있으면 계열 안의 차이는 세지 않는다 (→ 45%)
//   ③ 약한 낱말 세 칸은 빼기 — 「그대로 두」(손대지 않고 감추기)·「세척」(오염)·
//      「강도」(침입 위장, 압력 강도에 울린다)는 은폐 아닌 문장에서 운다 (→ 30%)
// 남은 30%(88건)를 열둘 뽑아 읽으니 아홉·열이 진짜 모자란 선언이었다 — CASE016
// 「노후 장비의 자체 결함으로 오작동한 것처럼」에 사고 위장 칸 0, CASE147 주사기를
// 의료폐기물에 섞는데 흉기 처분 없음. 정밀도 75~80%. 오탐은 선언을 한 칸 더해 푼다.
export const COVER_UP_ACCIDENT_FAMILY = new Set([
  'false_accident',
  'accident_equipment_failure',
  'accident_victim_error',
  'accident_victim_health',
  'accident_environment',
]);
export const COVER_UP_NARROW_WEAK = new Set([
  'concealment_without_staging',
  'contamination',
  'false_intrusion',
]);

export interface CoverUpGap {
  key: string;
  label: string;
  matched: string;
}

/** 선언(`cover_up_method`)이 있는데 `cover_up` 문장에서 폴백이 더 잡는 칸. 선언이 없으면 빈 배열(폴백이 그대로 센다). */
export function coverUpDeclarationGaps(
  fullTruth: Record<string, unknown> | undefined,
): CoverUpGap[] {
  const declared = fullTruth?.cover_up_method;
  if (!Array.isArray(declared) || declared.length === 0) return [];
  const text = typeof fullTruth?.cover_up === 'string' ? fullTruth.cover_up : '';
  if (!text) return [];
  const declSet = new Set(declared.filter((k): k is string => typeof k === 'string'));
  const declaresAccident = [...declSet].some((k) => COVER_UP_ACCIDENT_FAMILY.has(k));
  const gaps: CoverUpGap[] = [];
  for (const [key, label, pattern] of COVER_UP_METHODS) {
    if (declSet.has(key) || COVER_UP_NARROW_WEAK.has(key)) continue;
    if (declaresAccident && COVER_UP_ACCIDENT_FAMILY.has(key)) continue;
    const hit = pattern.exec(text);
    if (hit) gaps.push({ key, label, matched: hit[0] });
  }
  return gaps;
}
